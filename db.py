IS_POSTGRES = bool(settings.database_url)


@contextmanager
def get_connection():
    if IS_POSTGRES:
        import psycopg
        from psycopg.rows import dict_row

        conn = psycopg.connect(settings.database_url, row_factory=dict_row)
    else:
        conn = sqlite3.connect(settings.database_path)
        conn.row_factory = sqlite3.Row

    try:
        yield conn
        conn.commit()
    finally:
        conn.close()


def _execute(conn, query: str, params: Iterable[Any] | None = None):
    if IS_POSTGRES:
        query = query.replace("?", "%s")
    return conn.execute(query, tuple(params or ()))


def _row_get(row: Any, key: str, default: Any = None) -> Any:
    if row is None:
        return default
    if isinstance(row, dict):
        return row.get(key, default)
    try:
        return row[key]
    except (KeyError, IndexError, TypeError):
        return default


def init_db() -> None:
    if IS_POSTGRES:
        with get_connection() as conn:
            for statement in POSTGRES_SCHEMA:
                conn.execute(statement)
        return

    with get_connection() as conn:
        conn.executescript(SQLITE_SCHEMA)
        _ensure_sqlite_columns(conn)


def _ensure_sqlite_columns(conn) -> None:
    existing = {row["name"] for row in conn.execute("PRAGMA table_info(companies)").fetchall()}
    if "fax" not in existing:
        conn.execute("ALTER TABLE companies ADD COLUMN fax TEXT")
    if "latitude" not in existing:
        conn.execute("ALTER TABLE companies ADD COLUMN latitude REAL")
    if "longitude" not in existing:
        conn.execute("ALTER TABLE companies ADD COLUMN longitude REAL")


