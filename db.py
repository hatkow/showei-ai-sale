def send_count_by_company() -> dict[int, int]:
    with get_connection() as conn:
        rows = _execute(
            conn,
            """
            SELECT company_id, COUNT(*) AS send_count
            FROM send_logs
            GROUP BY company_id
            """,
        ).fetchall()
    return {int(_row_get(row, "company_id")): int(_row_get(row, "send_count")) for row in rows}
