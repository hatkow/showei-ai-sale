def update_company_contact(
    company_id: int,
    email: str | None = None,
    contact_url: str | None = None,
    fax: str | None = None,
) -> None:
    fields = ["updated_at = ?"]
    values: list[Any] = [now_iso()]
    if email is not None:
        fields.insert(0, "email = NULLIF(?, '')")
        values.insert(0, email)
    if contact_url is not None:
        fields.insert(0, "contact_url = NULLIF(?, '')")
        values.insert(0, contact_url)
    if fax is not None:
        fields.insert(0, "fax = NULLIF(?, '')")
        values.insert(0, fax)

    values.append(company_id)
    with get_connection() as conn:
        _execute(conn, f"UPDATE companies SET {', '.join(fields)} WHERE id = ?", values)


